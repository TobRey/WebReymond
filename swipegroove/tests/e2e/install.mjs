import { browser, BASE, check } from './pw.mjs';
import fs from 'node:fs';
const b = await browser();
const page = await b.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
await page.goto(BASE + '/');
check(page.url().includes('/groove/install'), 'Weiterleitung zum Installer');
await page.fill('input[name=base_url]', BASE);
await page.fill('input[name=db_host]', '127.0.0.1');
await page.fill('input[name=db_name]', 'swipegroove_e2e');
await page.fill('input[name=db_user]', 'sg');
await page.fill('input[name=db_pass]', 'sgpass');
await page.fill('input[name=spotify_client_id]', 'abcdef0123456789abcdef0123456789');
await page.fill('input[name=openai_api_key]', 'sk-local-test');
await page.fill('input[name=stripe_secret_key]', 'sk_test_local');
await page.fill('input[name=stripe_price_id]', 'price_local');
await page.fill('input[name=stripe_webhook_secret]', 'whsec_local');
await page.fill('input[name=setup_key]', 'local-setup-key-123456');
await page.screenshot({ path: process.env.SG_SHOTS + '/00-installer.png', fullPage: true });
await page.click('button[type=submit]');
await page.waitForSelector('text=Installation abgeschlossen');
const html = await page.content();
check(html.includes(BASE + '/auth/spotify/callback'), 'Callback-URL wird angezeigt');
check(html.includes(BASE + '/webhooks/stripe'), 'Webhook-URL wird angezeigt');
await page.screenshot({ path: process.env.SG_SHOTS + '/01-installed.png', fullPage: true });
check(fs.existsSync('/home/user/WebReymond/swipegroove/config/config.php'), 'config.php geschrieben');
// Installer gesperrt
const r = await page.goto(BASE + '/install');
check(r.status() === 403, 'Installer nach Installation gesperrt (403)');
await b.close();
console.log('INSTALL OK');
