/** Klassen, die im Bild eine Person bezeichnen (wie früher COCO „person“). */
export const PERSON_CLASSES = new Set(['Person', 'Man', 'Woman', 'Boy', 'Girl']);

/**
 * Körperteile werden nicht gezeichnet: Ein Rahmen um jedes Auge, jede Nase
 * und jede Hand würde das Bild zumüllen. Gesichter kommen von face-api,
 * Hände von MediaPipe – beide viel genauer.
 */
export const HIDDEN_CLASSES = new Set(ROWS.filter((r) => r[2] === 'body').map((r) => r[0]));

/** Reihenfolge = Ausgabereihenfolge des Modells. */
export const OIV7 = ROWS.map(([id, de, group]) => ({
  id,
  de,
  group,
  generic: GENERIC.has(id),
  person: PERSON_CLASSES.has(id),
  hidden: HIDDEN_CLASSES.has(id),
}));

const BY_ID = new Map(OIV7.map((entry) => [entry.id, entry]));

/** Eintrag zu einem Modellnamen, mit Rückfall für Unbekanntes. */
export function oiv7(id) {
  return (
    BY_ID.get(id) ?? { id, de: id, group: 'misc', generic: false, person: false, hidden: false }
  );
}

/** Deutscher Name eines Detektorlabels. */
export function labelDe(id) {
  return oiv7(id).de;
}
